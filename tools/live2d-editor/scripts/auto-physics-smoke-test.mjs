import assert from "node:assert/strict";
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptRoot = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptRoot, "..");

const appJs = await fs.readFile(path.join(projectRoot, "src", "app.js"), "utf8");
const html = await fs.readFile(path.join(projectRoot, "index.html"), "utf8");
const readme = await fs.readFile(path.join(projectRoot, "README.md"), "utf8");

assert.match(html, /id="autoPhysicsRules"/, "Auto Physics button should exist");
assert.match(html, /자동 물리/, "Auto Physics button should be visible in Korean");
assert.match(appJs, /autoPhysicsRules: document\.querySelector\("#autoPhysicsRules"\)/, "Auto Physics button should be wired in elements");
assert.match(appJs, /function autoPhysicsRules\(\{ confirmReplace = true \} = \{\}\)/, "Auto Physics handler should exist");
assert.match(appJs, /function buildAutoPhysicsRules\(\)/, "Auto Physics should build generated rules");
assert.match(appJs, /function autoPhysicsRoleSpec\(param, role, influenceEntry\)/, "Auto Physics should use parameter role specs");
assert.match(appJs, /function autoPhysicsTemplateForRole\(role\)/, "Auto Physics should define role templates");
assert.match(appJs, /case "breath":[\s\S]*case "hair":[\s\S]*case "gaze_x":/, "Auto Physics should cover breath, hair, and gaze roles");
assert.match(appJs, /manualRules = physics\.rules\.filter\(\(rule\) => !isAutoPhysicsRule\(rule\)\)/, "Auto Physics should preserve manual rules");
assert.match(appJs, /autoGenerated: true/, "Auto Physics generated rules should be marked");
assert.match(appJs, /autoPhysicsKind/, "Auto Physics generated rules should record their kind");
assert.match(appJs, /autoGenerated: rule\?\.autoGenerated === true \|\| rule\?\.auto_generated === true/, "normalization should preserve auto-generated physics metadata");
assert.match(appJs, /elements\.autoPhysicsRules\.addEventListener\("click"/, "Auto Physics button should be interactive");
assert.match(readme, /Use `Auto Physics`/, "README should document Auto Physics");

console.log("Auto Physics smoke test passed.");
